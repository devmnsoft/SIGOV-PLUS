-- Jornada auditável de inspeção e tratamento de divergências de recebimento.
-- Idempotente e preserva recebimentos legados sem alegar equivalência de comandos.
do $$
begin
 alter table sigov.compras_empresarial_recebimento add column if not exists inspecao_hash varchar(64);
exception when undefined_table then
 raise exception 'Tabela canônica sigov.compras_empresarial_recebimento ausente.';
end $$;

create table if not exists sigov.compras_empresarial_recebimento_divergencia (
 id bigint generated by default as identity primary key,
 tenant_id uuid not null,
 recebimento_id uuid not null,
 recebimento_item_id bigint not null,
 quantidade_rejeitada numeric(18,4) not null check (quantidade_rejeitada > 0),
 motivo varchar(1000) not null check (length(trim(motivo)) > 0),
 situacao varchar(24) not null default 'ABERTA' check (situacao in ('ABERTA','EM_TRATAMENTO','ENCERRADA')),
 responsavel_id uuid null,
 providencia varchar(40) null,
 andamento text null,
 resultado text null,
 justificativa_encerramento text null,
 encerrada_em timestamptz null,
 version bigint not null default 1,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 created_by text not null,
 updated_by text not null,
 correlation_id text null,
 constraint fk_comp_recb_div_recb foreign key (tenant_id,recebimento_id) references sigov.compras_empresarial_recebimento(tenant_id,id),
 constraint fk_comp_recb_div_item foreign key (tenant_id,recebimento_item_id) references sigov.compras_empresarial_recebimento_item(tenant_id,id),
 constraint ck_comp_recb_div_encerramento check ((situacao <> 'ENCERRADA' and encerrada_em is null) or (situacao = 'ENCERRADA' and encerrada_em is not null and length(trim(coalesce(resultado,''))) > 0 and length(trim(coalesce(justificativa_encerramento,''))) > 0)),
 unique (tenant_id,recebimento_item_id)
);
create index if not exists ix_comp_recb_div_fila on sigov.compras_empresarial_recebimento_divergencia(tenant_id,situacao,created_at desc,id desc);
create index if not exists ix_comp_recb_div_responsavel on sigov.compras_empresarial_recebimento_divergencia(tenant_id,responsavel_id,situacao) where situacao <> 'ENCERRADA';

create table if not exists sigov.compras_empresarial_recebimento_divergencia_evento (
 id bigint generated by default as identity primary key,
 tenant_id uuid not null,
 divergencia_id bigint not null,
 tipo varchar(50) not null,
 detalhes jsonb null,
 usuario_id uuid not null,
 ocorrido_em timestamptz not null default now(),
 correlation_id text null,
 constraint fk_comp_recb_div_evento foreign key (divergencia_id) references sigov.compras_empresarial_recebimento_divergencia(id)
);
create index if not exists ix_comp_recb_div_evento_historico on sigov.compras_empresarial_recebimento_divergencia_evento(tenant_id,divergencia_id,ocorrido_em,id);
