-- RC50.87: núcleo SaaS MNSOFT, IAM por cliente e tributos multi-esfera.
-- Aditiva, idempotente e sem integrações financeiras ou judiciais simuladas.
CREATE SCHEMA IF NOT EXISTS sigov;

CREATE TABLE IF NOT EXISTS sigov.saas_plano (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, codigo varchar(40) NOT NULL UNIQUE,
 nome varchar(120) NOT NULL, periodicidade varchar(12) NOT NULL, valor numeric(18,2) NOT NULL,
 ativo boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (periodicidade IN ('mensal','anual','contrato')), CHECK (valor >= 0)
);

CREATE TABLE IF NOT EXISTS sigov.saas_cliente (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL UNIQUE, entidade_id bigint NOT NULL,
 razao_social varchar(200) NOT NULL, nome_fantasia varchar(160), cnpj varchar(14) NOT NULL UNIQUE,
 esfera_governo varchar(12) NOT NULL, tipo_entidade varchar(30) NOT NULL, orgao_superior_id bigint,
 unidade_gestora_id bigint, unidade_executora_id bigint, hierarquia_administrativa varchar(200),
 abrangencia_territorial varchar(120), uf char(2), municipio varchar(160), regiao varchar(120), jurisdicao varchar(160),
 responsavel_institucional varchar(160) NOT NULL, email_administrativo varchar(254) NOT NULL, telefone varchar(30),
 dominio varchar(253), plano_id bigint REFERENCES sigov.saas_plano(id), status varchar(20) NOT NULL DEFAULT 'em_implantacao',
 motivo_bloqueio text, data_bloqueio timestamptz, data_desbloqueio timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), created_by bigint NOT NULL, updated_by bigint NOT NULL,
 CHECK (cnpj ~ '^[0-9]{14}$'), CHECK (esfera_governo IN ('municipal','estadual','federal','consorcio','outro')),
 CHECK (tipo_entidade IN ('prefeitura','camara','secretaria','sefaz','ministerio','autarquia','fundacao','fundo','empresa_publica','consorcio','outro')),
 CHECK (status IN ('em_implantacao','ativo','suspenso','bloqueado','cancelado')),
 CHECK ((status NOT IN ('suspenso','bloqueado','cancelado')) OR length(trim(coalesce(motivo_bloqueio,''))) >= 10)
);
CREATE INDEX IF NOT EXISTS ix_saas_cliente_contexto ON sigov.saas_cliente(tenant_id, entidade_id, esfera_governo);

CREATE TABLE IF NOT EXISTS sigov.saas_cliente_modulo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cliente_id bigint NOT NULL REFERENCES sigov.saas_cliente(id), modulo_chave varchar(100) NOT NULL,
 contratado boolean NOT NULL DEFAULT true, bloqueado boolean NOT NULL DEFAULT false, motivo_bloqueio text, updated_at timestamptz NOT NULL DEFAULT now(), updated_by bigint NOT NULL,
 UNIQUE(cliente_id, modulo_chave), CHECK (NOT bloqueado OR length(trim(coalesce(motivo_bloqueio,''))) >= 10)
);
CREATE TABLE IF NOT EXISTS sigov.saas_cliente_funcionalidade (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cliente_id bigint NOT NULL REFERENCES sigov.saas_cliente(id), funcionalidade_chave varchar(140) NOT NULL,
 contratada boolean NOT NULL DEFAULT true, bloqueada boolean NOT NULL DEFAULT false, motivo_bloqueio text, updated_at timestamptz NOT NULL DEFAULT now(), updated_by bigint NOT NULL,
 UNIQUE(cliente_id, funcionalidade_chave), CHECK (NOT bloqueada OR length(trim(coalesce(motivo_bloqueio,''))) >= 10)
);
CREATE TABLE IF NOT EXISTS sigov.saas_plano_modulo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, plano_id bigint NOT NULL REFERENCES sigov.saas_plano(id), modulo_chave varchar(100) NOT NULL, UNIQUE(plano_id, modulo_chave)
);
CREATE TABLE IF NOT EXISTS sigov.saas_plano_funcionalidade (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, plano_id bigint NOT NULL REFERENCES sigov.saas_plano(id), funcionalidade_chave varchar(140) NOT NULL, UNIQUE(plano_id, funcionalidade_chave)
);
CREATE TABLE IF NOT EXISTS sigov.saas_cobranca (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cliente_id bigint NOT NULL REFERENCES sigov.saas_cliente(id), competencia date NOT NULL,
 vencimento date NOT NULL, valor numeric(18,2) NOT NULL, status varchar(15) NOT NULL DEFAULT 'aberta', observacao text,
 created_at timestamptz NOT NULL DEFAULT now(), created_by bigint NOT NULL, updated_at timestamptz NOT NULL DEFAULT now(), updated_by bigint NOT NULL,
 CHECK (valor >= 0), CHECK (status IN ('aberta','paga','vencida','cancelada','renegociada')), UNIQUE(cliente_id, competencia)
);
CREATE INDEX IF NOT EXISTS ix_saas_cobranca_cliente_status ON sigov.saas_cobranca(cliente_id,status,vencimento);
CREATE TABLE IF NOT EXISTS sigov.saas_bloqueio (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cliente_id bigint NOT NULL REFERENCES sigov.saas_cliente(id), usuario_id bigint,
 modulo_chave varchar(100), funcionalidade_chave varchar(140), tipo varchar(25) NOT NULL, motivo text NOT NULL,
 ativo boolean NOT NULL DEFAULT true, bloqueado_at timestamptz NOT NULL DEFAULT now(), bloqueado_by bigint NOT NULL,
 desbloqueado_at timestamptz, desbloqueado_by bigint, justificativa_desbloqueio text,
 CHECK (tipo IN ('cliente','usuario','modulo','funcionalidade')), CHECK (length(trim(motivo)) >= 10),
 CHECK (ativo OR (desbloqueado_at IS NOT NULL AND desbloqueado_by IS NOT NULL AND length(trim(coalesce(justificativa_desbloqueio,''))) >= 10))
);
CREATE TABLE IF NOT EXISTS sigov.saas_auditoria_admin (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, cliente_id bigint REFERENCES sigov.saas_cliente(id), ator_usuario_id bigint NOT NULL,
 acao varchar(100) NOT NULL, recurso varchar(100) NOT NULL, recurso_id bigint, resultado varchar(20) NOT NULL,
 justificativa text, correlation_id varchar(80) NOT NULL, occurred_at timestamptz NOT NULL DEFAULT now(),
 CHECK (resultado IN ('sucesso','negado','erro'))
);

CREATE TABLE IF NOT EXISTS sigov.identidade_usuario_documento (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, usuario_id bigint NOT NULL,
 cpf_hash char(64) NOT NULL, cpf_cifrado bytea NOT NULL, cpf_final char(4) NOT NULL, email_verificado_at timestamptz,
 ativo boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(tenant_id, cpf_hash), CHECK (cpf_final ~ '^[0-9]{4}$')
);
CREATE TABLE IF NOT EXISTS sigov.identidade_login_evento (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint, entidade_id bigint, usuario_id bigint,
 identificador_hash char(64) NOT NULL, ip_hash char(64), user_agent_sanitizado varchar(200), sucesso boolean NOT NULL,
 motivo_generico varchar(80) NOT NULL, occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_identidade_login_evento_contexto ON sigov.identidade_login_evento(tenant_id,occurred_at DESC);
CREATE TABLE IF NOT EXISTS sigov.identidade_perfil_cliente (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, nome varchar(100) NOT NULL,
 descricao varchar(300) NOT NULL, perfil_base_id bigint REFERENCES sigov.identidade_perfil_cliente(id), ativo boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(), created_by bigint NOT NULL, updated_by bigint NOT NULL,
 UNIQUE(tenant_id,nome)
);
CREATE TABLE IF NOT EXISTS sigov.identidade_perfil_permissao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, perfil_id bigint NOT NULL REFERENCES sigov.identidade_perfil_cliente(id),
 modulo_chave varchar(100) NOT NULL, tela_chave varchar(140) NOT NULL, acao varchar(20) NOT NULL, permitida boolean NOT NULL DEFAULT false,
 updated_at timestamptz NOT NULL DEFAULT now(), updated_by bigint NOT NULL, UNIQUE(perfil_id,tela_chave,acao),
 CHECK (acao IN ('visualizar','criar','editar','excluir','aprovar','cancelar','exportar','administrar'))
);
CREATE TABLE IF NOT EXISTS sigov.identidade_usuario_perfil_cliente (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, usuario_id bigint NOT NULL,
 perfil_id bigint NOT NULL REFERENCES sigov.identidade_perfil_cliente(id), ativo boolean NOT NULL DEFAULT true,
 atribuido_at timestamptz NOT NULL DEFAULT now(), atribuido_by bigint NOT NULL, UNIQUE(tenant_id,usuario_id,perfil_id)
);
CREATE TABLE IF NOT EXISTS sigov.identidade_sessao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, usuario_id bigint NOT NULL,
 token_hash char(64) NOT NULL UNIQUE, criada_at timestamptz NOT NULL DEFAULT now(), expira_at timestamptz NOT NULL,
 encerrada_at timestamptz, motivo_encerramento varchar(80), CHECK (expira_at > criada_at)
);

-- Cadastros e movimentos tributários sempre carregam o contexto operacional completo.
CREATE TABLE IF NOT EXISTS sigov.tributo_parametro_esfera (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, exercicio_id bigint NOT NULL,
 esfera_governo varchar(10) NOT NULL, orgao_id bigint, unidade_gestora_id bigint, unidade_executora_id bigint,
 chave varchar(100) NOT NULL, valor_json jsonb NOT NULL, vigencia_inicio date NOT NULL, vigencia_fim date,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (esfera_governo IN ('municipal','estadual','federal')), CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio),
 UNIQUE(tenant_id,entidade_id,exercicio_id,esfera_governo,chave,vigencia_inicio)
);
CREATE TABLE IF NOT EXISTS sigov.tributo_tipo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, exercicio_id bigint NOT NULL,
 esfera_governo varchar(10) NOT NULL, orgao_id bigint, unidade_gestora_id bigint, unidade_executora_id bigint,
 codigo varchar(30) NOT NULL, nome varchar(160) NOT NULL, regra_calculo_json jsonb NOT NULL, ativo boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (esfera_governo IN ('municipal','estadual','federal')), UNIQUE(tenant_id,entidade_id,exercicio_id,codigo)
);
CREATE TABLE IF NOT EXISTS sigov.tributo_contribuinte (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, exercicio_id bigint NOT NULL,
 esfera_governo varchar(10) NOT NULL, orgao_id bigint, unidade_gestora_id bigint, unidade_executora_id bigint,
 pessoa_id bigint NOT NULL, inscricao varchar(40) NOT NULL, status varchar(20) NOT NULL DEFAULT 'ativo',
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (esfera_governo IN ('municipal','estadual','federal')), CHECK (status IN ('ativo','inativo','bloqueado')), UNIQUE(tenant_id,entidade_id,inscricao)
);
CREATE TABLE IF NOT EXISTS sigov.tributo_lancamento (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, exercicio_id bigint NOT NULL,
 esfera_governo varchar(10) NOT NULL, orgao_id bigint, unidade_gestora_id bigint, unidade_executora_id bigint,
 contribuinte_id bigint NOT NULL REFERENCES sigov.tributo_contribuinte(id), tributo_tipo_id bigint NOT NULL REFERENCES sigov.tributo_tipo(id),
 emissao date NOT NULL, vencimento date NOT NULL, base_calculo numeric(18,4) NOT NULL, valor_lancado numeric(18,2) NOT NULL,
 saldo numeric(18,2) NOT NULL, regra_aplicada_json jsonb NOT NULL, memoria_calculo_json jsonb NOT NULL, status varchar(20) NOT NULL DEFAULT 'aberto',
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (esfera_governo IN ('municipal','estadual','federal')), CHECK (base_calculo >= 0 AND valor_lancado >= 0 AND saldo >= 0 AND saldo <= valor_lancado),
 CHECK (vencimento >= emissao), CHECK (status IN ('aberto','pago','cancelado','parcelado','divida_ativa'))
);
CREATE INDEX IF NOT EXISTS ix_tributo_lancamento_contexto ON sigov.tributo_lancamento(tenant_id,entidade_id,esfera_governo,exercicio_id,status);
CREATE TABLE IF NOT EXISTS sigov.tributo_pagamento (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, exercicio_id bigint NOT NULL,
 esfera_governo varchar(10) NOT NULL, orgao_id bigint, unidade_gestora_id bigint, unidade_executora_id bigint,
 lancamento_id bigint NOT NULL REFERENCES sigov.tributo_lancamento(id), pago_at timestamptz NOT NULL, valor numeric(18,2) NOT NULL,
 referencia_integracao varchar(120) NOT NULL, estornado_at timestamptz, justificativa_estorno text,
 created_at timestamptz NOT NULL DEFAULT now(), created_by bigint NOT NULL,
 CHECK (esfera_governo IN ('municipal','estadual','federal')), CHECK (valor > 0),
 CHECK (estornado_at IS NULL OR length(trim(coalesce(justificativa_estorno,''))) >= 10)
);
CREATE TABLE IF NOT EXISTS sigov.tributo_baixa (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, exercicio_id bigint NOT NULL,
 esfera_governo varchar(10) NOT NULL, orgao_id bigint, unidade_gestora_id bigint, unidade_executora_id bigint,
 lancamento_id bigint NOT NULL REFERENCES sigov.tributo_lancamento(id), tipo varchar(20) NOT NULL, valor numeric(18,2) NOT NULL,
 justificativa text NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), created_by bigint NOT NULL,
 CHECK (esfera_governo IN ('municipal','estadual','federal')), CHECK (tipo IN ('pagamento','manual','estorno')), CHECK (valor > 0), CHECK (length(trim(justificativa)) >= 10)
);
CREATE TABLE IF NOT EXISTS sigov.tributo_parcelamento (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, exercicio_id bigint NOT NULL,
 esfera_governo varchar(10) NOT NULL, orgao_id bigint, unidade_gestora_id bigint, unidade_executora_id bigint,
 contribuinte_id bigint NOT NULL REFERENCES sigov.tributo_contribuinte(id), entrada numeric(18,2) NOT NULL DEFAULT 0,
 quantidade_parcelas integer NOT NULL, saldo_original numeric(18,2) NOT NULL, juros numeric(18,2) NOT NULL DEFAULT 0,
 multa numeric(18,2) NOT NULL DEFAULT 0, correcao numeric(18,2) NOT NULL DEFAULT 0, status varchar(20) NOT NULL DEFAULT 'ativo',
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK (esfera_governo IN ('municipal','estadual','federal')), CHECK (entrada >= 0 AND quantidade_parcelas > 0 AND saldo_original > 0 AND juros >= 0 AND multa >= 0 AND correcao >= 0),
 CHECK (status IN ('ativo','quitado','rompido','cancelado'))
);
CREATE TABLE IF NOT EXISTS sigov.tributo_divida_ativa (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, exercicio_id bigint NOT NULL,
 esfera_governo varchar(10) NOT NULL, orgao_id bigint, unidade_gestora_id bigint, unidade_executora_id bigint,
 lancamento_id bigint NOT NULL REFERENCES sigov.tributo_lancamento(id), inscricao varchar(50) NOT NULL, inscrito_at timestamptz NOT NULL,
 notificado_at timestamptz NOT NULL, valor_inscrito numeric(18,2) NOT NULL, saldo numeric(18,2) NOT NULL, elegibilidade_verificada boolean NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'inscrita', created_at timestamptz NOT NULL DEFAULT now(), created_by bigint NOT NULL,
 CHECK (esfera_governo IN ('municipal','estadual','federal')), CHECK (valor_inscrito > 0 AND saldo >= 0 AND saldo <= valor_inscrito),
 CHECK (elegibilidade_verificada), CHECK (notificado_at <= inscrito_at), CHECK (status IN ('inscrita','parcelada','quitada','cancelada','protestada','execucao')),
 UNIQUE(tenant_id,entidade_id,inscricao)
);
CREATE TABLE IF NOT EXISTS sigov.tributo_certidao (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id bigint NOT NULL, entidade_id bigint NOT NULL, exercicio_id bigint NOT NULL,
 esfera_governo varchar(10) NOT NULL, orgao_id bigint, unidade_gestora_id bigint, unidade_executora_id bigint,
 contribuinte_id bigint NOT NULL REFERENCES sigov.tributo_contribuinte(id), tipo varchar(30) NOT NULL, codigo_verificacao varchar(80) NOT NULL UNIQUE,
 emitida_at timestamptz NOT NULL DEFAULT now(), valida_ate date NOT NULL, conteudo_hash char(64) NOT NULL,
 CHECK (esfera_governo IN ('municipal','estadual','federal')), CHECK (tipo IN ('negativa','positiva','positiva_efeito_negativa'))
);

