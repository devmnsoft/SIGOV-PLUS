-- Compatibilidade aditiva entre o workflow legado (RC pós-protocolo) e a plataforma RC49.
-- Este arquivo é deliberadamente idempotente: colunas legadas permanecem disponíveis.
create schema if not exists sigov;

create table if not exists sigov.workflow_definicao (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null,
    nome varchar(120) not null,
    descricao varchar(500),
    modulo varchar(40) not null,
    status varchar(20) not null default 'RASCUNHO',
    versao_atual integer not null default 0,
    created_by bigint,
    updated_by bigint,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    is_deleted boolean not null default false
);
alter table sigov.workflow_definicao
    add column if not exists tenant_id bigint,
    add column if not exists nome varchar(120),
    add column if not exists descricao varchar(500),
    add column if not exists modulo varchar(40),
    add column if not exists status varchar(20) default 'RASCUNHO',
    add column if not exists versao_atual integer default 0,
    add column if not exists created_by bigint,
    add column if not exists updated_by bigint,
    add column if not exists created_at timestamptz default now(),
    add column if not exists updated_at timestamptz default now(),
    add column if not exists is_deleted boolean default false;

do $compatibility$
begin
    if to_regclass('sigov.workflow_etapa') is not null then
        alter table sigov.workflow_etapa
            add column if not exists workflow_definicao_id bigint,
            add column if not exists descricao varchar(400),
            add column if not exists tipo varchar(40),
            add column if not exists responsavel_id bigint,
            add column if not exists grupo_responsavel_id bigint,
            add column if not exists ordem integer,
            add column if not exists prazo_horas integer,
            add column if not exists inicial boolean not null default false,
            add column if not exists final boolean not null default false,
            add column if not exists exige_justificativa boolean not null default false,
            add column if not exists exige_anexo boolean not null default false,
            add column if not exists exige_aprovacao boolean not null default false,
            add column if not exists permite_retorno boolean not null default false,
            add column if not exists formulario_definicao_id bigint;

        insert into sigov.workflow_definicao (tenant_id, nome, descricao, modulo, status, versao_atual)
        select distinct e.tenant_id, 'Workflow legado',
               'Definição preservada automaticamente a partir do contrato legado.',
               'PROCESSOS', 'PUBLICADO', 1
          from sigov.workflow_etapa e
         where not exists (
             select 1 from sigov.workflow_definicao d
              where d.tenant_id = e.tenant_id and d.nome = 'Workflow legado'
         );

        update sigov.workflow_etapa e
           set workflow_definicao_id = d.id
          from sigov.workflow_definicao d
         where e.workflow_definicao_id is null
           and d.tenant_id = e.tenant_id
           and d.nome = 'Workflow legado';
        update sigov.workflow_etapa set tipo = 'TAREFA' where tipo is null or btrim(tipo) = '';
        update sigov.workflow_etapa set nome = 'Etapa ' || id where nome is null or btrim(nome) = '';
        with ordenadas as (
            select id, row_number() over (partition by tenant_id, workflow_definicao_id order by id)::integer as nova_ordem
              from sigov.workflow_etapa
        )
        update sigov.workflow_etapa e set ordem = o.nova_ordem
          from ordenadas o where e.id = o.id and e.ordem is null;

        if exists (select 1 from sigov.workflow_etapa where workflow_definicao_id is null) then
            raise exception using
                errcode = '23502',
                message = 'Compatibilidade RC49: não foi possível mapear workflow_etapa.workflow_definicao_id para todas as linhas.',
                hint = 'Corrija tenant_id nulo/inválido nas etapas legadas antes de reaplicar.';
        end if;
        create index if not exists ix_workflow_etapa_tenant_workflow
            on sigov.workflow_etapa(tenant_id, workflow_definicao_id, ordem);
    end if;
end
$compatibility$;

do $compatibility$
begin
    if to_regclass('sigov.workflow_transicao') is not null then
        alter table sigov.workflow_transicao
            add column if not exists workflow_definicao_id bigint,
            add column if not exists de_etapa_id bigint,
            add column if not exists para_etapa_id bigint,
            add column if not exists condicao varchar(300),
            add column if not exists acao varchar(80),
            add column if not exists permissao_necessaria varchar(100),
            add column if not exists mensagem_usuario varchar(240);
        if exists (select 1 from information_schema.columns where table_schema='sigov' and table_name='workflow_transicao' and column_name='etapa_origem_id') then
            execute 'update sigov.workflow_transicao set de_etapa_id = etapa_origem_id where de_etapa_id is null';
        end if;
        if exists (select 1 from information_schema.columns where table_schema='sigov' and table_name='workflow_transicao' and column_name='etapa_destino_id') then
            execute 'update sigov.workflow_transicao set para_etapa_id = etapa_destino_id where para_etapa_id is null';
        end if;
        if to_regclass('sigov.workflow_etapa') is not null then
            update sigov.workflow_transicao t
               set workflow_definicao_id = origem.workflow_definicao_id
              from sigov.workflow_etapa origem
             where t.workflow_definicao_id is null
               and origem.id = t.de_etapa_id and origem.tenant_id = t.tenant_id;
            update sigov.workflow_transicao t
               set workflow_definicao_id = destino.workflow_definicao_id
              from sigov.workflow_etapa destino
             where t.workflow_definicao_id is null
               and destino.id = t.para_etapa_id and destino.tenant_id = t.tenant_id;
        end if;
        update sigov.workflow_transicao set acao = 'AVANCAR' where acao is null or btrim(acao) = '';
    end if;
end
$compatibility$;

create table if not exists sigov.workflow_versao (
    id bigint generated by default as identity primary key, tenant_id bigint not null,
    workflow_definicao_id bigint, numero integer, status varchar(20),
    conteudo_json jsonb default '{}'::jsonb, publicado_por bigint,
    publicado_em timestamptz, created_at timestamptz default now()
);
alter table sigov.workflow_versao
    add column if not exists tenant_id bigint,
    add column if not exists workflow_definicao_id bigint,
    add column if not exists numero integer,
    add column if not exists status varchar(20),
    add column if not exists conteudo_json jsonb default '{}'::jsonb,
    add column if not exists publicado_por bigint,
    add column if not exists publicado_em timestamptz,
    add column if not exists created_at timestamptz default now();
insert into sigov.workflow_versao (tenant_id, workflow_definicao_id, numero, status, conteudo_json, publicado_em)
select d.tenant_id, d.id, 1, 'PUBLICADO', '{}'::jsonb, now()
  from sigov.workflow_definicao d
 where not exists (select 1 from sigov.workflow_versao v where v.workflow_definicao_id=d.id and v.tenant_id=d.tenant_id);
update sigov.workflow_definicao d set versao_atual=1
 where coalesce(d.versao_atual,0)=0
   and exists (select 1 from sigov.workflow_versao v where v.workflow_definicao_id=d.id);

create table if not exists sigov.workflow_evento (
    id bigint generated by default as identity primary key, tenant_id bigint,
    workflow_instancia_id bigint, tipo varchar(40), de_etapa_id bigint,
    para_etapa_id bigint, justificativa varchar(1000), usuario_id bigint,
    dados_json jsonb default '{}'::jsonb, correlation_id uuid, created_at timestamptz default now()
);
alter table sigov.workflow_evento
    add column if not exists tenant_id bigint,
    add column if not exists workflow_instancia_id bigint,
    add column if not exists tipo varchar(40),
    add column if not exists de_etapa_id bigint,
    add column if not exists para_etapa_id bigint,
    add column if not exists justificativa varchar(1000),
    add column if not exists usuario_id bigint,
    add column if not exists dados_json jsonb default '{}'::jsonb,
    add column if not exists correlation_id uuid,
    add column if not exists created_at timestamptz default now();
