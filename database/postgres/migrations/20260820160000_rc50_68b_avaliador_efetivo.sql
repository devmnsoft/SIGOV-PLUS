-- RC50.68B: integridade dos vínculos e trilha consultável das decisões.
-- Idempotente, aditiva e sem alterar identificadores legados.
alter table sigov.usuario_grupo
    add column if not exists ativo boolean not null default true;
alter table sigov.grupo_perfil
    add column if not exists ativo boolean not null default true;
alter table sigov.perfil_permissao
    add column if not exists ativo boolean not null default true,
    add column if not exists is_deleted boolean not null default false;
alter table sigov.perfil_acesso
    add column if not exists sistemico boolean not null default false,
    add column if not exists motivo_inativacao varchar(500);

do $$ begin
  if not exists (select 1 from pg_constraint where conname='ck_usuario_grupo_vigencia') then
    alter table sigov.usuario_grupo add constraint ck_usuario_grupo_vigencia check (vigencia_fim is null or vigencia_inicio is null or vigencia_fim >= vigencia_inicio);
  end if;
  if not exists (select 1 from pg_constraint where conname='ck_grupo_perfil_vigencia') then
    alter table sigov.grupo_perfil add constraint ck_grupo_perfil_vigencia check (vigencia_fim is null or vigencia_inicio is null or vigencia_fim >= vigencia_inicio);
  end if;
end $$;

create table if not exists sigov.autorizacao_decisao_auditoria (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null,
    tenant_id bigint,
    entidade_id bigint,
    exercicio_id bigint,
    unidade_id bigint,
    modulo varchar(60) not null,
    recurso varchar(160) not null,
    acao varchar(80) not null,
    valor_solicitado numeric(18,2),
    permitido boolean not null,
    efeito varchar(10),
    motivo varchar(80) not null,
    correlation_id varchar(100),
    origem varchar(80),
    perfil_id bigint,
    vinculo_permissao_id bigint,
    limite_alcada numeric(18,2),
    decidido_em_utc timestamptz not null default now(),
    constraint ck_autorizacao_auditoria_efeito check (efeito is null or efeito in ('PERMITIR','NEGAR')),
    constraint ck_autorizacao_auditoria_valor check (valor_solicitado is null or valor_solicitado >= 0)
);

create index if not exists ix_autorizacao_decisao_usuario_recurso
 on sigov.autorizacao_decisao_auditoria(usuario_id,modulo,recurso,acao,decidido_em_utc desc);
create index if not exists ix_autorizacao_decisao_escopo
 on sigov.autorizacao_decisao_auditoria(tenant_id,entidade_id,exercicio_id,unidade_id,decidido_em_utc desc);
create index if not exists ix_usuario_grupo_avaliacao
 on sigov.usuario_grupo(usuario_id,tenant_id,entidade_id,exercicio_id,unidade_id,vigencia_fim) where ativo and not is_deleted;
create index if not exists ix_grupo_perfil_avaliacao
 on sigov.grupo_perfil(grupo_acesso_id,tenant_id,entidade_id,exercicio_id,unidade_id,vigencia_fim) where ativo and not is_deleted;
create index if not exists ix_perfil_permissao_avaliacao
 on sigov.perfil_permissao(perfil_acesso_id,permissao_id,efeito,tenant_id,entidade_id,exercicio_id,unidade_id,vigencia_fim) where ativo and not is_deleted;

update sigov.perfil_acesso
   set sistemico=true, updated_at=coalesce(updated_at,now())
 where codigo_externo in ('SUPERADMIN','ADMIN_TENANT','DIRETOR_GESTOR','COORDENADOR_AREA','OPERACIONAL_USUARIO','FINANCEIRO','AUDITOR_LEITURA','ATENDIMENTO')
   and not is_deleted;
