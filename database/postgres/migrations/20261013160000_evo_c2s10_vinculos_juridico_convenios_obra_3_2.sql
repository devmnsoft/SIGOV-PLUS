-- 1) Relaxamento nao-destrutivo das tabelas legadas compartilhadas pela frente ----
--    juridico_consulta: filial (recurso) referencia a consulta original preservada,
--    custo de honorario e prazo de resposta (BR-10.1). Maximo de 1 filial por
--    consulta original por tenant (uq parcial; a validacao nomeada e no comando).
alter table sigov.juridico_consulta add column if not exists consulta_pai_id bigint;
alter table sigov.juridico_consulta add column if not exists custo_honorario numeric(18,4) not null default 0;
alter table sigov.juridico_consulta add column if not exists prazo_resposta date;
do $$
begin
  if not exists (select 1 from pg_constraint c join pg_class r on r.oid = c.conrelid where r.relname = 'juridico_consulta' and c.conname = 'fk_juridico_consulta_pai') then
    alter table sigov.juridico_consulta add constraint fk_juridico_consulta_pai foreign key (consulta_pai_id) references sigov.juridico_consulta(id);
  end if;
end
$$;
create unique index if not exists ux_juridico_consulta_filial on sigov.juridico_consulta(tenant_id, consulta_pai_id) where consulta_pai_id is not null and ativo and not is_deleted;
--    juridico_processo: origem do contencioso (contrato/convênio/trabalhista/tributário)
--    alimenta o marcador JURIDICO do contrato e o bloqueio de prorrogação (BR-10.2).
alter table sigov.juridico_processo add column if not exists origem_tipo varchar(30);
alter table sigov.juridico_processo add column if not exists origem_id bigint;
alter table sigov.juridico_processo drop constraint if exists ck_juridico_processo_origem;
alter table sigov.juridico_processo add constraint ck_juridico_processo_origem check (origem_tipo is null or (origem_tipo)::text = any (array['CONTRATO','CONVENIO','TRABALHISTA','TRIBUTARIO','OUTRA']));
create index if not exists ix_juridico_processo_origem on sigov.juridico_processo(tenant_id, origem_tipo, origem_id) where origem_tipo is not null and ativo and not is_deleted;
--    convenio_contrapartida: chave de idempotencia do registro de contrapartida
--    (BR-7.8). Este modulo usa a convencao entity_id/deleted_at (sem ativo/is_deleted).
alter table sigov.convenio_contrapartida add column if not exists chave_idempotencia varchar(150);
create unique index if not exists ux_convenio_contrapartida_chave on sigov.convenio_contrapartida(tenant_id, chave_idempotencia) where chave_idempotencia is not null and deleted_at is null;

-- 2) Vinculo consulta juridica x contratacao (BR-10.1) ---------------------------
--    Consulta tipada vinculada a processo de contratacao (tipo PARECER/IMPUGNACAO/
--    DEFESA/COBRANCA) com referencia do numero administrativo e chave de idempotencia
--    (reprocesso com mesmo conteudo retorna o vinculo existente; divergente conflita).
create table if not exists sigov.compras_juridico_consulta_vinculo(
 id bigint generated by default as identity primary key,
 tenant_id bigint not null,
 entidade_id bigint,
 consulta_id bigint not null,
 processo_compras_id bigint not null,
 tipo_consulta varchar(30) not null check ((tipo_consulta)::text = any (array['PARECER','IMPUGNACAO','DEFESA','COBRANCA'])),
 referencia_numero varchar(120) not null,
 chave_idempotencia varchar(150),
 auditoria jsonb not null default '[]'::jsonb,
 correlation_id uuid not null default gen_random_uuid(),
 ativo boolean not null default true,
 is_deleted boolean not null default false,
 created_at timestamptz not null default now(),
 created_by bigint,
 updated_at timestamptz not null default now(),
 updated_by bigint
);
create unique index if not exists ux_compras_juridico_consulta_vinculo_chave on sigov.compras_juridico_consulta_vinculo(tenant_id, chave_idempotencia) where chave_idempotencia is not null and ativo and not is_deleted;
create index if not exists ix_compras_juridico_consulta_vinculo_processo on sigov.compras_juridico_consulta_vinculo(processo_compras_id) where ativo and not is_deleted;

-- 3) Condicionantes de parecer condicionado (BR-10.1) -----------------------------
--    Decisao condicionada impede o proximo passo da contratacao (homologacao) enquanto
--    houver condicao ABERTA; satisfazer exige justificativa e fecha a condicao; com
--    todas satisfeitas a consulta vira RESOLVIDA (a original e preservada no recurso).
create table if not exists sigov.juridico_parecer_condicao(
 id bigint generated by default as identity primary key,
 tenant_id bigint not null,
 entidade_id bigint,
 parecer_id bigint not null,
 descricao text not null,
 status varchar(20) not null default 'ABERTA' check ((status)::text = any (array['ABERTA','SATISFEITA'])),
 satisfeita_em timestamptz,
 justificativa text,
 auditoria jsonb not null default '[]'::jsonb,
 correlation_id uuid not null default gen_random_uuid(),
 ativo boolean not null default true,
 is_deleted boolean not null default false,
 created_at timestamptz not null default now(),
 created_by bigint,
 updated_at timestamptz not null default now(),
 updated_by bigint
);
create index if not exists ix_juridico_parecer_condicao_parecer on sigov.juridico_parecer_condicao(parecer_id) where ativo and not is_deleted;

-- 4) Ledger de vinculos cruzados entre modulos (BR-7.8/BR-10.2/BR-10.5) -----------
--    Atos registrados que ligam o contrato a alvos (instrumento de convênio, contencioso
--    juridico, obra). Toda quebra de vinculo exige justificativa e ato registrado
--    (estado QUITADO com justificativa, data e ator — sem delete fisico). O saldo do
--    encerramento de convênio e a cascata de bloqueio derivam daqui (banco = autoridade).
create table if not exists sigov.compras_vinculo_externo(
 id bigint generated by default as identity primary key,
 tenant_id bigint not null,
 entidade_id bigint,
 contrato_id bigint not null,
 alvo_modulo varchar(40) not null check ((alvo_modulo)::text = any (array['CONVENIO','OBRA','JURIDICO_CONTENCIOSO'])),
 alvo_id bigint not null,
 status varchar(20) not null default 'ATIVO' check ((status)::text = any (array['ATIVO','QUITADO'])),
 chave_idempotencia varchar(150),
 justificativa_quitacao text,
 quitado_em timestamptz,
 quitado_por bigint,
 auditoria jsonb not null default '[]'::jsonb,
 correlation_id uuid not null default gen_random_uuid(),
 ativo boolean not null default true,
 is_deleted boolean not null default false,
 created_at timestamptz not null default now(),
 created_by bigint,
 updated_at timestamptz not null default now(),
 updated_by bigint
);
create unique index if not exists ux_compras_vinculo_externo_chave on sigov.compras_vinculo_externo(tenant_id, chave_idempotencia) where chave_idempotencia is not null and ativo and not is_deleted;
create index if not exists ix_compras_vinculo_externo_alvo on sigov.compras_vinculo_externo(alvo_modulo, alvo_id) where ativo and not is_deleted;
create index if not exists ix_compras_vinculo_externo_contrato on sigov.compras_vinculo_externo(contrato_id) where ativo and not is_deleted;

-- 5) Parametro do modulo CONVENIOS (banco = autoridade, regra 11) ------------------
--    Execucao minima (pct) dos repasses recebidos exigida para registrar prestacao de
--    contas (BR-10.3). A contrapartida ja e parametrizada POR INSTRUMENTO
--    (valor_contrapartida do instrumento, regra do contrato BR-7.8) — sem parametro global.
insert into sigov.parametro_modulo(modulo,codigo,nome,descricao,tipo,valor_padrao,sensivel,ordem,ativo) values
 ('CONVENIOS','CONVENIO_PRESTACAO_EXECUCAO_MINIMA_PCT','Execucao minima para prestacao de contas (pct)','BR-10.3: prestacao de contas (parcial/final) so registrada com execucao minima parametrica dos recursos recebidos (default 70%)','INTEGER','70',false,230,true)
on conflict do nothing;

-- 6) Catalogo das chaves novas dos atos S10 (modulos juridico/convenios) + vinculo
--    SUPERADMIN (padrao S7/funcional: autoridade pelo codigo externo SUPERADMIN ativo).
--    Reutilizadas SEM seed nova (documentado no contrato BR-7.x):
--    compras.contrapartida.registrar (registrar/aplicar/quitar contrapartida e vinculo
--    convênio — C2S7), obras.medicao.registrar (homologar medicao), compras.contrato.
--    execucao.fiscalizar (quitar vinculo / fiscalizacao), compras.auditoria.visualizar
--    (GET de vinculos), e as chaves das gates ja consumidas pelos comandos existentes
--    (homologacao.executar / contrato.prorrogar).
insert into sigov.permissao(modulo,chave,recurso,acao,descricao,ativo,is_deleted)
select v.modulo,v.chave,v.recurso,v.acao,v.descricao,true,false from (values
 ('juridico','juridico.consulta.criar','consulta','criar','Abrir consulta juridica vinculada a contratacao (PARECER/IMPUGNACAO/DEFESA/COBRANCA) com prazo de resposta, custo honorario e filial por recurso - BR-10.1'),
 ('juridico','juridico.parecer.emitir','parecer','emitir','Emitir parecer com conclusao FAVORECIMENTO/IMPROCEDENCIA/CONDICIONADO + condicionantes e satisfazer condicoes abertas - BR-10.1'),
 ('juridico','juridico.contencioso.abrir','contencioso','abrir','Abrir contencioso (ativo/passivo) com origem (contrato/convenio/trabalhista/tributario), valor da causa e eventos append-only - BR-10.2'),
 ('juridico','juridico.contencioso.desfechar','contencioso','desfechar','Desfechar contencioso (TRANSACAO/JUGADO/DESISTENCIA) com custas e ato registrado; limpa o marcador juridico do contrato - BR-10.2'),
 ('convenios','convenios.instrumento.encerrar','instrumento','encerrar','Encerrar instrumento de convenio com gates de contratos ativos vinculados e saldo de execucao nao justificado exigindo justificativa - BR-10.3/BR-10.5'),
 ('convenios','convenios.prestacao.registrar','prestacao','registrar','Registrar prestacao de contas (parcial/final) com execucao minima parametrica dos recursos recebidos - BR-10.3')
) v(modulo,chave,recurso,acao,descricao)
where not exists(select 1 from sigov.permissao p where p.chave=v.chave);

insert into sigov.perfil_permissao(perfil_acesso_id,permissao_id,efeito,ativo,is_deleted)
select pa.id,p.id,'PERMITIR',true,false
 from sigov.perfil_acesso pa cross join sigov.permissao p
where pa.codigo_externo='SUPERADMIN' and pa.ativo and not pa.is_deleted
  and p.ativo and not p.is_deleted
  and p.chave in ('juridico.consulta.criar','juridico.parecer.emitir','juridico.contencioso.abrir','juridico.contencioso.desfechar','convenios.instrumento.encerrar','convenios.prestacao.registrar')
on conflict (perfil_acesso_id,permissao_id) do update set efeito='PERMITIR',ativo=true,is_deleted=false;

-- 7) Pos-condicao C2S10-POSTCOND: falha explicita se faltar qualquer artefato (regra 13)
do $$
declare
  n_chaves int;
  n_perfis int;
  n_vinculos int;
begin
  if not exists(select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='sigov' and c.relname='compras_juridico_consulta_vinculo')
  or not exists(select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='sigov' and c.relname='juridico_parecer_condicao')
  or not exists(select 1 from pg_class c join pg_namespace n on n.oid=c.relnamespace where n.nspname='sigov' and c.relname='compras_vinculo_externo') then
    raise exception 'C2S10-POSTCOND: tabela canonical ausente (vinculo consulta/condicao parecer/vinculo externo)';
  end if;
  if not exists(select 1 from information_schema.columns c where c.table_schema='sigov' and c.table_name='juridico_consulta' and c.column_name='consulta_pai_id')
  or not exists(select 1 from information_schema.columns c where c.table_schema='sigov' and c.table_name='juridico_processo' and c.column_name='origem_tipo')
  or not exists(select 1 from information_schema.columns c where c.table_schema='sigov' and c.table_name='convenio_contrapartida' and c.column_name='chave_idempotencia') then
    raise exception 'C2S10-POSTCOND: coluna de relaxamento ausente (consulta_pai_id/origem_tipo/chave_idempotencia)';
  end if;
  select count(1) into n_chaves
    from sigov.permissao
   where ativo and not is_deleted
     and chave in ('juridico.consulta.criar','juridico.parecer.emitir','juridico.contencioso.abrir','juridico.contencioso.desfechar','convenios.instrumento.encerrar','convenios.prestacao.registrar');
  if n_chaves <> 6 then
    raise exception 'C2S10-POSTCOND: catalogo de permissoes S10 incompleto (% <> 6)', n_chaves;
  end if;
  select count(1) into n_perfis from sigov.perfil_acesso where codigo_externo='SUPERADMIN' and ativo and not is_deleted;
  if n_perfis = 0 then
    raise exception 'C2S10-POSTCOND: nenhum perfil SUPERADMIN ativo no banco (autoridade ausente)';
  end if;
  select count(1) into n_vinculos
    from sigov.perfil_permissao pp
    join sigov.permissao p on p.id = pp.permissao_id
    join sigov.perfil_acesso pa on pa.id = pp.perfil_acesso_id
   where pa.codigo_externo='SUPERADMIN' and pa.ativo and not pa.is_deleted
     and pp.ativo and not pp.is_deleted
     and p.chave in ('juridico.consulta.criar','juridico.parecer.emitir','juridico.contencioso.abrir','juridico.contencioso.desfechar','convenios.instrumento.encerrar','convenios.prestacao.registrar');
  if n_vinculos <> n_perfis * 6 then
    raise exception 'C2S10-POSTCOND: vinculos SUPERADMIN S10 incompletos (% <> %*6)', n_vinculos, n_perfis;
  end if;
  if not exists(select 1 from sigov.parametro_modulo p where p.modulo='CONVENIOS' and p.codigo='CONVENIO_PRESTACAO_EXECUCAO_MINIMA_PCT' and p.ativo and not p.is_deleted) then
    raise exception 'C2S10-POSTCOND: parametro CONVENIO_PRESTACAO_EXECUCAO_MINIMA_PCT ausente';
  end if;
  if not exists(select 1 from sigov.permissao p where p.ativo and not p.is_deleted and p.chave in
      ('compras.contrapartida.registrar','obras.medicao.registrar','compras.contrato.execucao.fiscalizar','compras.auditoria.visualizar','compras.homologacao.executar','compras.contrato.prorrogar')) then
    raise exception 'C2S10-POSTCOND: catalogo de permissoes reutilizadas incompleto (contrapartida/medicao/fiscalizar/auditoria/homologacao/prorrogar)';
  end if;
end
$$;
