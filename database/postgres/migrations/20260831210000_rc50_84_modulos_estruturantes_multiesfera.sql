-- Complemento idempotente e sem dados demonstrativos.
do $$ begin
  if to_regclass('sigov.tenant') is null then raise exception 'Schema obrigatório ausente: sigov.tenant'; end if;
  if to_regclass('sigov.entidade') is null then raise exception 'Schema obrigatório ausente: sigov.entidade'; end if;
end $$;

do $$ declare t text; begin
  foreach t in array array[
    'governanca_entidade_hierarquia','governanca_parametro_esfera','protocolo_movimentacao',
    'ouvidoria_manifestacao_fluxo','compras_planejamento_contratacao','compras_processo_fase',
    'contrato_gestao_fiscalizacao','financeiro_execucao_orcamentaria',
    'tributo_lancamento_historico','rh_servidor_vinculo_historico','qualidade_modulo_estruturante'
  ] loop
    execute format('create table if not exists sigov.%I (
      id bigint generated by default as identity primary key,
      tenant_id bigint not null,
      entidade_id bigint not null,
      esfera_governo varchar(12) not null,
      tipo_entidade varchar(60) not null,
      orgao_id bigint,
      orgao_superior_id bigint,
      unidade_gestora_id bigint,
      unidade_executora_id bigint,
      exercicio_id bigint,
      referencia_id bigint,
      referencia_pai_id bigint,
      tipo varchar(40) not null,
      status varchar(32) not null default ''ATIVO'',
      titulo varchar(240) not null,
      descricao text,
      jurisdicao varchar(160),
      uf char(2),
      municipio varchar(160),
      regiao varchar(160),
      prioridade varchar(10),
      data_inicio date,
      data_fim date,
      prazo_em date,
      valor numeric(18,2),
      percentual numeric(5,2),
      sigiloso boolean not null default false,
      dados jsonb not null default ''{}''::jsonb,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now(),
      created_by bigint,
      updated_by bigint,
      constraint ck_%s_esfera check (esfera_governo in (''municipal'',''estadual'',''federal'')),
      constraint ck_%s_tipo_entidade check (length(trim(tipo_entidade)) between 2 and 60),
      constraint ck_%s_tipo check (length(trim(tipo)) between 2 and 40),
      constraint ck_%s_status check (status in (''ATIVO'',''INATIVO'',''RASCUNHO'',''ABERTO'',''EM_ANALISE'',''EM_TRAMITACAO'',''SUSPENSO'',''CONCLUIDO'',''CANCELADO'',''INDEFERIDO'')),
      constraint ck_%s_prioridade check (prioridade is null or prioridade in (''BAIXA'',''MEDIA'',''ALTA'',''URGENTE'')),
      constraint ck_%s_valor check (valor is null or valor >= 0),
      constraint ck_%s_percentual check (percentual is null or percentual between 0 and 100),
      constraint ck_%s_datas check (data_fim is null or data_inicio is null or data_fim >= data_inicio),
      constraint ck_%s_territorio check (uf is null or uf ~ ''^[A-Z]{2}$'')
    )', t,t,t,t,t,t,t,t,t,t);
    execute format('create index if not exists ix_%s_contexto on sigov.%I (tenant_id, entidade_id, esfera_governo, status)',t,t);
    execute format('create index if not exists ix_%s_unidade on sigov.%I (tenant_id, entidade_id, unidade_gestora_id, unidade_executora_id)',t,t);
    execute format('create index if not exists ix_%s_exercicio_data on sigov.%I (tenant_id, entidade_id, exercicio_id, created_at desc)',t,t);
    execute format('create index if not exists ix_%s_orgao on sigov.%I (tenant_id, entidade_id, orgao_id, status)',t,t);
  end loop;
end $$;

-- FKs de contexto são adicionadas somente quando o contrato referenciado existe.
do $$ declare t text; begin
  foreach t in array array[
    'governanca_entidade_hierarquia','governanca_parametro_esfera','protocolo_movimentacao',
    'ouvidoria_manifestacao_fluxo','compras_planejamento_contratacao','compras_processo_fase',
    'contrato_gestao_fiscalizacao','financeiro_execucao_orcamentaria',
    'tributo_lancamento_historico','rh_servidor_vinculo_historico','qualidade_modulo_estruturante'
  ] loop
    if not exists (select 1 from pg_constraint where conname='fk_'||t||'_tenant') then
      execute format('alter table sigov.%I add constraint %I foreign key (tenant_id) references sigov.tenant(id)',t,'fk_'||t||'_tenant');
    end if;
    if not exists (select 1 from pg_constraint where conname='fk_'||t||'_entidade') then
      execute format('alter table sigov.%I add constraint %I foreign key (entidade_id) references sigov.entidade(id)',t,'fk_'||t||'_entidade');
    end if;
  end loop;
end $$;

insert into sigov.permissao(chave,nome,modulo,ativo,created_at)
select chave,nome,modulo,true,now() from (values
 ('ESTRUTURANTES_GOVERNANCA_VIEW','Estruturantes: visualizar governança','governanca'),
 ('ESTRUTURANTES_PROTOCOLO_MANAGE','Estruturantes: gerenciar protocolo, Ouvidoria e SIC','protocolo'),
 ('ESTRUTURANTES_COMPRAS_MANAGE','Estruturantes: gerenciar compras, licitações e contratos','compras'),
 ('ESTRUTURANTES_FINANCEIRO_MANAGE','Estruturantes: gerenciar orçamento, financeiro e contabilidade','financeiro'),
 ('ESTRUTURANTES_TRIBUTOS_MANAGE','Estruturantes: gerenciar tributos e arrecadação','tributos'),
 ('ESTRUTURANTES_RH_MANAGE','Estruturantes: gerenciar RH e folha','rh'),
 ('ESTRUTURANTES_RELATORIO_EXPORT','Estruturantes: exportar relatórios multi-esfera','relatorios')
) p(chave,nome,modulo)
on conflict(chave) do update set nome=excluded.nome,modulo=excluded.modulo,ativo=true;
