 execute format('alter table %s add column if not exists exercicio_id bigint',target); execute format('alter table %s add column if not exists codigo varchar(100)',target);
 execute format('alter table %s add column if not exists numero bigint',target); execute format('alter table %s add column if not exists ano integer',target);
 execute format('alter table %s add column if not exists tipo varchar(80)',target); execute format('alter table %s add column if not exists status varchar(40)',target);
 execute format('alter table %s add column if not exists titulo varchar(300)',target); execute format('alter table %s add column if not exists descricao text',target);
 execute format('alter table %s add column if not exists referencia_id bigint',target); execute format('alter table %s add column if not exists responsavel_id bigint',target);
 execute format('alter table %s add column if not exists data_referencia timestamptz',target); execute format('alter table %s add column if not exists prazo_at timestamptz',target);
 execute format('alter table %s add column if not exists justificativa text',target); execute format('alter table %s add column if not exists sigiloso boolean',target);
 execute format('alter table %s add column if not exists hash_sha256 varchar(64)',target); execute format('alter table %s add column if not exists codigo_validacao varchar(100)',target);
 execute format('alter table %s add column if not exists dados jsonb',target); execute format('alter table %s add column if not exists auditoria jsonb',target);
 execute format('alter table %s add column if not exists correlation_id uuid',target); execute format('alter table %s add column if not exists ativo boolean',target);
 execute format('alter table %s add column if not exists is_deleted boolean',target); execute format('alter table %s add column if not exists created_at timestamptz',target);
 execute format('alter table %s add column if not exists updated_at timestamptz',target); execute format('alter table %s add column if not exists deleted_at timestamptz',target);
 execute format('alter table %s add column if not exists created_by bigint',target); execute format('alter table %s add column if not exists updated_by bigint',target); execute format('alter table %s add column if not exists deleted_by bigint',target);
 execute format('update %s set status=coalesce(status,''ATIVO''), dados=coalesce(dados,''{}''::jsonb), auditoria=coalesce(auditoria,''{}''::jsonb), correlation_id=coalesce(correlation_id,gen_random_uuid()), ativo=coalesce(ativo,true), is_deleted=coalesce(is_deleted,false), sigiloso=coalesce(sigiloso,false), created_at=coalesce(created_at,now())',target);
