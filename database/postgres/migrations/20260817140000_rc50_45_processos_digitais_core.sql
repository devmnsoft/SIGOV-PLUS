-- SIGOV+ RC50.45 - invariantes de protocolo e processos digitais.

create table if not exists sigov.processo_numero_sequencial (
    id bigint generated by default as identity primary key,
    tenant_id bigint not null,
    entidade_id bigint not null,
    exercicio_id bigint,
    tipo varchar(80),
    status varchar(40) not null default 'ATIVO',
    ativo boolean not null default true,
    is_deleted boolean not null default false
);
alter table sigov.processo_numero_sequencial add column if not exists ativo boolean not null default true;
alter table sigov.processo_numero_sequencial add column if not exists is_deleted boolean not null default false;
alter table sigov.processo_numero_sequencial add column if not exists status varchar(40) not null default 'ATIVO';

create unique index if not exists ux_processo_numero_escopo
    on sigov.processo_numero_sequencial (tenant_id, entidade_id, exercicio_id, tipo)
    where is_deleted = false and ativo = true;
create unique index if not exists ux_processo_codigo_publico
    on sigov.processo_digital (tenant_id, codigo)
    where codigo is not null and is_deleted = false;
create index if not exists ix_processo_prazo_operacional
    on sigov.processo_prazo (tenant_id, prazo_at, status)
    where is_deleted = false and ativo = true;
create index if not exists ix_protocolo_codigo_consulta
    on sigov.protocolo_externo (tenant_id, codigo)
    where codigo is not null and is_deleted = false and sigiloso = false;
