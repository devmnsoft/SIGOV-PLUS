-- Conferência de faturas, match trilateral (pedido x recebimento aceito x fatura),
-- rastreabilidade de itens, histórico e concorrência operacional.
-- Multi-esfera: municípios, estados e União. Idempotente.

alter table sigov.compras_empresarial_fatura
    add column if not exists tipo_documento varchar(30) not null default 'NOTA_FISCAL',
    add column if not exists chave_acesso varchar(60) null,
    add column if not exists data_emissao date null,
    add column if not exists data_vencimento date null,
    add column if not exists valor_itens numeric(18,2) not null default 0,
    add column if not exists valor_desconto numeric(18,2) not null default 0,
    add column if not exists valor_frete numeric(18,2) not null default 0,
    add column if not exists valor_seguro numeric(18,2) not null default 0,
    add column if not exists valor_outras_despesas numeric(18,2) not null default 0,
    add column if not exists valor_liquido numeric(18,2) not null default 0,
    add column if not exists observacoes text null,
    add column if not exists justificativa text null,
    add column if not exists decidido_por text null,
    add column if not exists decidido_em timestamptz null,
    add column if not exists motivo_rejeicao text null;

create unique index if not exists ux_ce_fatura_chave_acesso
    on sigov.compras_empresarial_fatura(tenant_id, chave_acesso)
    where chave_acesso is not null and chave_acesso <> '';

create table if not exists sigov.compras_empresarial_fatura_item (
    id bigint generated by default as identity primary key,
    tenant_id uuid not null,
    fatura_id uuid not null references sigov.compras_empresarial_fatura(id) on delete cascade,
    pedido_item_id bigint not null references sigov.compras_empresarial_pedido_item(id),
    quantidade numeric(18,4) not null check (quantidade > 0),
    valor_unitario numeric(18,4) not null check (valor_unitario >= 0),
    valor_total numeric(18,2) not null check (valor_total >= 0),
    created_at timestamptz not null default now(),
    unique(tenant_id, fatura_id, pedido_item_id)
);

create index if not exists ix_ce_fatura_item_pedido_item
    on sigov.compras_empresarial_fatura_item(tenant_id, pedido_item_id);

create table if not exists sigov.compras_empresarial_fatura_evento (
    id bigint generated by default as identity primary key,
    tenant_id uuid not null,
    fatura_id uuid not null references sigov.compras_empresarial_fatura(id) on delete cascade,
    tipo varchar(50) not null,
    detalhes jsonb null,
    usuario_id uuid not null,
    ocorrido_em timestamptz not null default now(),
    correlation_id text null
);

create index if not exists ix_ce_fatura_evento_timeline
    on sigov.compras_empresarial_fatura_evento(tenant_id, fatura_id, ocorrido_em);

create table if not exists sigov.compras_empresarial_fatura_idempotencia (
    tenant_id uuid not null,
    operacao varchar(60) not null,
    chave varchar(200) not null,
    fatura_id uuid not null,
    request_hash text not null,
    resultado jsonb null,
    created_at timestamptz not null default now(),
    primary key(tenant_id, operacao, chave)
);
