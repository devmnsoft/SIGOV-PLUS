-- RC-EVO-RH | 20261007100000 - migration grande RH/folha (idempotente).
-- Materializa no banco as precondicoes exigidas pela jornada real de ponto -> folha
-- (sections 4 a 8), sem alterar migrations publicadas (regra 8):
--   R1  Tabela sigov.rh_feriado - consumida pela apuracao real de ponto
--       (ListarFeriadosPeriodoAsync) e ainda inexistente; forma generica padrao RH
--       multi-esfera (regras 21-24): data_referencia NOT NULL; abrangimento
--       territorial/esfera em dados.esferaGoverno/uf/municipio/jurisdicao quando aplicavel.
--   R2  Parametro FOLHA/RUBRICAS_PONTO (JSON) com valor_padrao neutro '[]': tenants sem
--       catalogo falham explicitamente com RUBRICAS_AUSENTES na integracao (regra 13);
--       seed ficticio idempotente para tenants de desenvolvimento/homologacao (regras 9/10).
--   R3  Modulo 'rh' HABILITADO em sigov.tenant_modulo_contratado para os tenants dev.
--   R4  Catalogo de permissao rh.apuracao.reabrir + grants PERMITIR: administracao local
--       (ADMIN_TENANT/ADMINISTRADOR_TENANT/ADMIN_GERAL/ADMINISTRADOR_GERAL), cadeia
--       plataforma (ADMIN_PLATAFORMA_MNSOFT, escopo NULL) e coordenacao local
--       (COORDENADOR). O perfil SERVIDOR nao reabre: sem auto-aprovacao (section 5/6).
--   R5  Backfill idempotente das colunas estruturadas de sigov.rh_ponto_apuracao a partir
--       do jsonb dados (casings camel/Pascal legadas); nao destrutivo; no-op em dev.
-- Sem credencial literal; autoverificacao com falha explicita (regra 13).

create table if not exists sigov.rh_feriado (
  id bigint generated by default as identity primary key,
  tenant_id bigint not null, entidade_id bigint null, exercicio_id bigint null, servidor_id bigint null,
  usuario_id bigint null, competencia date null, periodo_inicio date null, periodo_fim date null,
  data_referencia date not null, tipo varchar(60) null, status varchar(40) not null default 'ATIVO',
  motivo text null, justificativa text null, descricao text null, resposta text null,
  ativo boolean not null default true, is_deleted boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz null, deleted_at timestamptz null,
  created_by bigint null, updated_by bigint null, deleted_by bigint null,
  auditoria jsonb not null default '{}'::jsonb, dados jsonb not null default '{}'::jsonb,
  correlation_id uuid null,
  constraint ck_rh_feriado_periodo check (periodo_fim is null or periodo_inicio is null or periodo_fim >= periodo_inicio)
);
create index if not exists ix_rh_feriado_tenant on sigov.rh_feriado (tenant_id);
create index if not exists ix_rh_feriado_tenant_deleted on sigov.rh_feriado (tenant_id,is_deleted);
create index if not exists ix_rh_feriado_data on sigov.rh_feriado (data_referencia);
create index if not exists ix_rh_feriado_status on sigov.rh_feriado (status);
create unique index if not exists ux_rh_feriado_unico on sigov.rh_feriado (tenant_id, data_referencia, (coalesce(tipo,'')), (coalesce(descricao,''))) where is_deleted = false;
comment on table sigov.rh_feriado is 'RC-EVO-RH: feriados usados pela apuracao de ponto; multi-esfera (NACIONAL/ESTADUAL/MUNICIPAL/UNIDADE) com abrangimento em dados quando aplicavel';

-- R1b) Feriados nacionais fixos de 2026 para os tenants de desenvolvimento/homologacao.
-- Datas fixas publicamente conhecidas (sem regra legal inventada); taxa, adicional ou
-- percentual nenhum - apenas a data, que e entrada da apuracao. Idempotente via arbiter.
insert into sigov.rh_feriado (tenant_id, data_referencia, tipo, status, descricao, dados)
select t.id, f.data_referencia, 'NACIONAL', 'ATIVO', f.descricao,
       jsonb_build_object('esferaGoverno', 'federal', 'natureza', 'NACIONAL', 'origem', 'SEED_FICTICIO_DEV')
from (values (date '2026-01-01','Confraternizacao Universal'),
             (date '2026-05-01','Dia do Trabalho'),
             (date '2026-11-15','Proclamacao da Republica'),
             (date '2026-12-25','Natal')) f(data_referencia, descricao)
cross join sigov.tenant t
where t.id in (1,3,4,5) and t.ativo and not t.is_deleted
on conflict (tenant_id, data_referencia, (coalesce(tipo,'')), (coalesce(descricao,''))) where is_deleted = false do nothing;

-- R3) Modulo 'rh' habilitado nos tenants de desenvolvimento/homologacao (seed, regras 9/10).
-- Nao reverte suspensao deliberada (SUSPENSO/CANCELADO permanece) em reexecucoes.
insert into sigov.tenant_modulo_contratado (tenant_id, modulo_codigo, status, contratado_em, vigencia_inicio, ativo)
select t.id, 'rh', 'HABILITADO', current_date, current_date, true
from sigov.tenant t
where t.id in (1,3,4,5) and t.ativo and not t.is_deleted
on conflict (tenant_id, modulo_codigo)
do update set status = case when tenant_modulo_contratado.status in ('SUSPENSO','CANCELADO')
                            then tenant_modulo_contratado.status else 'HABILITADO' end,
              ativo = true,
              vigencia_inicio = case when tenant_modulo_contratado.vigencia_inicio is null
                                     then current_date else tenant_modulo_contratado.vigencia_inicio end;

-- R2) Parametro FOLHA/RUBRICAS_PONTO (catalago de rubricas da integracao, section 7).
-- Fail-closed: padrao vazio => tenants sem catalogo recebem RUBRICAS_AUSENTES nomeada.
insert into sigov.parametro_modulo (modulo, codigo, nome, descricao, tipo, valor_padrao, sensivel, ordem)
values ('FOLHA','RUBRICAS_PONTO','Rubricas de lancamento de ponto na folha',
        'Array JSON [{codigo,nome,tipo(PROVENTO|DESCONTO),base(MINUTOS_TRABALHADOS|MINUTOS_INTERVALO|DIAS_FALTA),taxa}]. Ausente ou vazio gera falha explicita RUBRICAS_AUSENTES na integracao.',
        'JSON','[]',false,100)
on conflict (modulo,codigo) where is_deleted=false
do update set nome = excluded.nome, descricao = excluded.descricao, tipo = excluded.tipo, ativo = true, is_deleted = false;

do $rubricas$
declare
    v_parametro bigint;
    v_tenant_id bigint;
    -- Catalogo FICTICIO de desenvolvimento/homologacao (regras 9/10): taxas de exemplo,
    -- sem ligacao a legislacao, convenio ou plano de carreira.
    v_valores jsonb := '[{"codigo":"PONT-HOR","nome":"Horas trabalhadas (ponto)","tipo":"PROVENTO","base":"MINUTOS_TRABALHADOS","taxa":0.5},{"codigo":"PONT-INT","nome":"Intervalo fracionado (ponto)","tipo":"PROVENTO","base":"MINUTOS_INTERVALO","taxa":0.25},{"codigo":"PONT-FALTA","nome":"Dia de falta (ponto)","tipo":"DESCONTO","base":"DIAS_FALTA","taxa":100}]'::jsonb;
begin
    select id into v_parametro
      from sigov.parametro_modulo
     where modulo='FOLHA' and codigo='RUBRICAS_PONTO' and ativo and not is_deleted;

    for v_tenant_id in select id from sigov.tenant where id in (1,3,4,5) and ativo and not is_deleted loop
        if not exists (select 1 from sigov.parametro_modulo_valor
                       where tenant_id = v_tenant_id and parametro_id = v_parametro and not is_deleted) then
            insert into sigov.parametro_modulo_valor (tenant_id, parametro_id, valor, created_by, updated_by, correlation_id)
            values (v_tenant_id, v_parametro, v_valores, null, null, 'evo-rh-folha-seed');
            insert into sigov.parametro_modulo_historico (tenant_id, parametro_id, valor_anterior, valor_novo, usuario_id, correlation_id, auditoria)
            values (v_tenant_id, v_parametro, null, v_valores, null, 'evo-rh-folha-seed', '{"origem":"SEED_FICTICIO_DEV"}'::jsonb);
        end if;
    end loop;
end $rubricas$;

-- R4a) Catalogo: tuplo avaliado em codigo pelo CanAsync('rh.apuracao.reabrir').
insert into sigov.permissao (chave, descricao, modulo, recurso, acao, ativo)
values ('rh.apuracao.reabrir', 'Reabrir apuracao de ponto homologada (exige justificativa e valida a folha de destino)', 'rh', 'apuracao', 'reabrir', true)
on conflict (chave) do update set ativo = true, is_deleted = false;

-- R4b) Grants PERMITIR (mesmo padrao do evo_a01: G1 local / G2 plataforma / G4 operacao).
do $grants$
declare
    v_pa_plataforma bigint;
begin
    -- As triggers trg_* derivam tenant_id quando NULL (do perfil/grupo pai); sao desabilitadas
    -- apenas durante os upserts (DDL transacional: em falha, o rollback restaura o estado anterior).
    alter table sigov.perfil_permissao disable trigger user;

    -- Administracao local (escopo do proprio tenant).
    insert into sigov.perfil_permissao (perfil_acesso_id, permissao_id, tenant_id, entidade_id, exercicio_id, unidade_id, efeito, alcada_valor, justificativa, ativo, is_deleted, created_at, created_by, updated_at)
    select distinct pa.id, p.id, case when pa.sistemico then null::bigint else pa.tenant_id end, null::bigint, null::bigint, null::bigint, 'PERMITIR', null::numeric,
           'RC-EVO-RH: reabertura de apuracao homologada para administracao local do tenant',
           true, false, now(), null::bigint, now()
      from sigov.perfil_acesso pa
      join sigov.permissao p
        on p.chave = 'rh.apuracao.reabrir' and p.ativo and not p.is_deleted
     where pa.tenant_id is not null
       and pa.ativo and not pa.is_deleted
       and pa.codigo_externo in ('ADMIN_TENANT', 'ADMINISTRADOR_TENANT', 'ADMIN_GERAL', 'ADMINISTRADOR_GERAL')
    on conflict (perfil_acesso_id, permissao_id) do update
        set tenant_id = excluded.tenant_id, entidade_id = null, exercicio_id = null, unidade_id = null,
            vigencia_inicio = null, vigencia_fim = null, efeito = 'PERMITIR', alcada_valor = null,
            ativo = true, is_deleted = false, updated_at = now();

    -- Cadeia plataforma (escopo tenant_id NULL) - administracao global.
    select pa.id into strict v_pa_plataforma
      from sigov.perfil_acesso pa
     where pa.codigo_externo = 'ADMIN_PLATAFORMA_MNSOFT'
       and pa.ativo and not pa.is_deleted
     order by pa.id
     limit 1;

    insert into sigov.perfil_permissao (perfil_acesso_id, permissao_id, tenant_id, entidade_id, exercicio_id, unidade_id, efeito, alcada_valor, justificativa, ativo, is_deleted, created_at, created_by, updated_at)
    select distinct v_pa_plataforma, p.id, null::bigint, null::bigint, null::bigint, null::bigint, 'PERMITIR', null::numeric,
           'RC-EVO-RH: reabertura de apuracao homologada para administracao global (escopo plataforma)',
           true, false, now(), null::bigint, now()
      from sigov.permissao p
     where p.chave = 'rh.apuracao.reabrir' and p.ativo and not p.is_deleted
    on conflict (perfil_acesso_id, permissao_id) do update
        set tenant_id = null, entidade_id = null, exercicio_id = null, unidade_id = null,
            vigencia_inicio = null, vigencia_fim = null, efeito = 'PERMITIR', alcada_valor = null,
            ativo = true, is_deleted = false, updated_at = now();

    -- Coordenacao local nao-sistema. O SERVIDOR NAO recebe: reabrir apos homologacao e mais
    -- forte que aprovar/apurar e o mesmo servidor nunca reabre a propria competencia (sem auto-aprovacao).
    insert into sigov.perfil_permissao (perfil_acesso_id, permissao_id, tenant_id, entidade_id, exercicio_id, unidade_id, efeito, alcada_valor, justificativa, ativo, is_deleted, created_at, created_by, updated_at)
    select distinct pa.id, p.id, pa.tenant_id, null::bigint, null::bigint, null::bigint, 'PERMITIR', null::numeric,
           'RC-EVO-RH: reabertura de apuracao homologada para coordenacao local',
           true, false, now(), null::bigint, now()
      from sigov.perfil_acesso pa
      join sigov.permissao p
        on p.chave = 'rh.apuracao.reabrir' and p.ativo and not p.is_deleted
     where pa.tenant_id is not null
       and coalesce(pa.sistemico, false) = false
       and pa.ativo and not pa.is_deleted
       and pa.codigo_externo in ('COORDENADOR')
    on conflict (perfil_acesso_id, permissao_id) do update
        set tenant_id = excluded.tenant_id, entidade_id = null, exercicio_id = null, unidade_id = null,
            vigencia_inicio = null, vigencia_fim = null, efeito = 'PERMITIR', alcada_valor = null,
            ativo = true, is_deleted = false, updated_at = now();

    alter table sigov.perfil_permissao enable trigger user;

    -- Autoverificacao (falha explicita; regra 13).
    if not exists (select 1 from sigov.permissao
                   where chave = 'rh.apuracao.reabrir'
                     and btrim(coalesce(recurso, '')) = 'apuracao'
                     and btrim(coalesce(acao, '')) = 'reabrir'
                     and ativo and not is_deleted)
    then
        raise exception 'RC-EVO-RH 20261007100000: tuplo rh.apuracao.reabrir nao ficou satisfeito no catalogo';
    end if;

    if exists (select 1 from sigov.perfil_acesso
               where codigo_externo = 'ADMIN_PLATAFORMA_MNSOFT' and ativo and not is_deleted)
       and not exists (
            select 1 from sigov.perfil_permissao pp
            join sigov.perfil_acesso pa on pa.id = pp.perfil_acesso_id
            join sigov.permissao p on p.id = pp.permissao_id
            where pa.codigo_externo = 'ADMIN_PLATAFORMA_MNSOFT'
              and pp.tenant_id is null
              and upper(pp.efeito) = 'PERMITIR'
              and pp.ativo and not pp.is_deleted
              and p.ativo and not p.is_deleted
              and p.chave = 'rh.apuracao.reabrir')
    then
        raise exception 'RC-EVO-RH 20261007100000: cadeia plataforma sem grant de rh.apuracao.reabrir em escopo NULL';
    end if;
end $grants$;

-- R5) Backfill das colunas estruturadas da apuracao a partir do jsonb dados (upgrade legado).
-- Cada coluna so e preenchida quando vazia e o valor no jsonb e valido; nunca sobrescreve
-- dados ja estruturados nem altera linhas sem conteudo em dados (idempotente e nao destrutivo).
update sigov.rh_ponto_apuracao a
set servidor_id     = case when a.servidor_id is null and t.sid ~ '^[0-9]+$' then t.sid::bigint else a.servidor_id end,
    status          = case when btrim(coalesce(a.status, '')) = '' and t.st <> '' then t.st else a.status end,
    periodo_inicio  = case when a.periodo_inicio is null and t.pi ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' then t.pi::date else a.periodo_inicio end,
    periodo_fim     = case when a.periodo_fim is null and t.pf ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' then t.pf::date else a.periodo_fim end,
    data_referencia = case when a.data_referencia is null and t.dr ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}' then t.dr::date else a.data_referencia end,
    motivo          = case when btrim(coalesce(a.motivo, '')) = '' and t.mo <> '' then t.mo else a.motivo end,
    justificativa   = case when btrim(coalesce(a.justificativa, '')) = '' and t.ju <> '' then t.ju else a.justificativa end,
    updated_at      = case when (a.servidor_id is null and t.sid ~ '^[0-9]+$')
                             or (btrim(coalesce(a.status, '')) = '' and t.st <> '')
                             or (a.periodo_inicio is null and t.pi ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}')
                             or (a.periodo_fim is null and t.pf ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}')
                             or (a.data_referencia is null and t.dr ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}')
                             or (btrim(coalesce(a.motivo, '')) = '' and t.mo <> '')
                             or (btrim(coalesce(a.justificativa, '')) = '' and t.ju <> '')
                        then now() else a.updated_at end
from (
    select id,
           nullif(btrim(coalesce(dados->>'servidorId', dados->>'ServidorId', '')), '') as sid,
           nullif(btrim(coalesce(dados->>'status', dados->>'Status', '')), '') as st,
           nullif(btrim(coalesce(dados->>'periodoInicio', dados->>'PeriodoInicio', '')), '') as pi,
           nullif(btrim(coalesce(dados->>'periodoFim', dados->>'PeriodoFim', '')), '') as pf,
           nullif(btrim(coalesce(dados->>'dataReferencia', dados->>'DataReferencia', '')), '') as dr,
           nullif(btrim(coalesce(dados->>'motivo', dados->>'Motivo', '')), '') as mo,
           nullif(btrim(coalesce(dados->>'justificativa', dados->>'Justificativa', '')), '') as ju
      from sigov.rh_ponto_apuracao
     where is_deleted = false and coalesce(dados::text, '{}') not in ('{}', '')
) t
where a.id = t.id
  and (a.servidor_id is null
       or btrim(coalesce(a.status, '')) = ''
       or a.periodo_inicio is null
       or a.periodo_fim is null
       or a.data_referencia is null
       or btrim(coalesce(a.motivo, '')) = ''
       or btrim(coalesce(a.justificativa, '')) = '');

-- Autoverificacao final (falha explicita; regra 13).
do $check$
begin
    if not exists (select 1 from pg_class c
                   join pg_namespace n on n.oid = c.relnamespace
                   where n.nspname = 'sigov' and c.relname = 'rh_feriado')
    then
        raise exception 'RC-EVO-RH 20261007100000: tabela sigov.rh_feriado nao foi criada';
    end if;

    if not exists (select 1 from sigov.parametro_modulo
                   where modulo = 'FOLHA' and codigo = 'RUBRICAS_PONTO' and ativo and not is_deleted)
    then
        raise exception 'RC-EVO-RH 20261007100000: parametro FOLHA/RUBRICAS_PONTO ausente';
    end if;

    if exists (select 1 from sigov.tenant where id in (1,3,4,5) and ativo and not is_deleted)
       and exists (select 1 from sigov.tenant t
                   where t.id in (1,3,4,5) and t.ativo and not t.is_deleted
                     and not exists (select 1 from sigov.tenant_modulo_contratado tm
                                     where tm.tenant_id = t.id and tm.modulo_codigo = 'rh'
                                       and tm.status = 'HABILITADO' and tm.ativo))
    then
        raise exception 'RC-EVO-RH 20261007100000: modulo rh nao ficou HABILITADO em todos os tenants dev';
    end if;

    raise notice 'RC-EVO-RH 20261007100000 concluida: rh_feriado, RUBRICAS_PONTO, grants rh.apuracao.reabrir, backfill de apuracao.';
end $check$;
